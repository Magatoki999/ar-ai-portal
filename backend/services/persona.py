        "    このタグにはURLではなく、必ずIDの数字だけを入れてください"
        "（URLをタグの中や本文中に書く必要は一切ありません。実際の動画URLへの変換は"
        "システム側が自動で行います）。\n"
        "  - 結果の中に「動画ID: 数字」の行が**含まれていなかった場合**（プロンプトのみの記録）：\n"
