        "（直近の会話に出ていないだけで、データベースには記録されている可能性が高いため）。\n\n"
        "  ステップ1: プロンプト中のエピソードメモリまたは食事記録に [image:URL] が"
        "含まれているか確認する（「ごはん見せて」「あの時の食事」のような食事の写真依頼にも"
        "同じ判断を使う）。\n"
