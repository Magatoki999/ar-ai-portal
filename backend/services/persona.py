        "「今いる場所」のように、固有名詞ではなく指示語で場所を指している場合は、"
        "必ず ||SEARCH_LOCATION_PHOTO:HERE|| タグをセリフ末尾に追加する"
        "（場所名を無理に推測したり、ユーザーの発言をそのままタグに入れたりしないこと。"
        "「HERE」という文字列を厳密にそのまま使うこと）。\n"
        "    例: 'この辺りの写真、探してみますね！||SEARCH_LOCATION_PHOTO:HERE||'\n\n"
